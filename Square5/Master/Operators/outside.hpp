void input::outsidehoping( int i)
{
    int n = i;
    for(int k1=0; k1<N; k1++)
    {
        long long bi1=0;
        int id=0;
        for ( int j =0; j<N; j++)
        {
            int reminder = i%Ls;
            i=i/Ls;
            //======================//
            if(j==k1)
            {
                if (reminder<Ls-1)
                {
                    reminder+=1;
                    id++;
                }
            }
            //======================//
            bi1+=reminder*pow(Ls,j);
            //=======================//
        }

        //======================================//
        
        double sss=double(id);
        int q =int(bi1);// Decimal(bi1);
         H(q,n)+=hx/2.0*sss;
        
         H(n,q)=conj(H(q,n));
        //======================================//
        i=n;
    }
}



